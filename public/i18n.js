const DICTS = { en: EN, tr: TR };
const STORE_KEY = 'edge.lang';

let current = 'en';
try {
  const saved = localStorage.getItem(STORE_KEY);
  if (saved && DICTS[saved]) current = saved;
} catch { /* depolama kapali olabilir */ }

export const getLang = () => current;
export const locale = () => (current === 'tr' ? 'tr-TR' : 'en-GB');

export function setLang(lang) {
  if (!DICTS[lang]) return;
  current = lang;
  try { localStorage.setItem(STORE_KEY, lang); } catch { /* yoksay */ }
  document.documentElement.lang = lang;
}

export function t(key, vars) {
  const dict = DICTS[current] || EN;
  let text = dict[key] !== undefined ? dict[key] : (EN[key] !== undefined ? EN[key] : key);
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}

/** Static markup: elements carrying data-i18n / data-i18n-ph get translated. */
export function applyStaticText(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const label = t(el.dataset.i18nTitle);
    el.title = label;
    el.setAttribute('aria-label', label);
  }
  document.documentElement.lang = current;
}

